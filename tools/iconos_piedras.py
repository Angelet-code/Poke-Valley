# Iconos pixel art de las piedras evolutivas (modo aventura): una piedra facetada con el color y el símbolo de cada
# una dentro (gota, rayo, llama, hoja, copo), como las de los juegos. Píxel a píxel, 16×16, igual que tools/icono_hogar.py.
# Uso: python -I tools/iconos_piedras.py [carpeta_vistas_ampliadas]
