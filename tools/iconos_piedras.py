# Colores: contorno, brillo, claro, medio, sombra, símbolo.
PALETA = {
    'waterstone': ((28, 52, 96), (190, 232, 255), (110, 180, 240), (58, 120, 210), (36, 80, 160), (226, 246, 255)),
    'thunderstone': ((40, 84, 52), (210, 250, 200), (130, 210, 140), (72, 160, 96), (44, 112, 70), (255, 222, 60)),
    'firestone': ((110, 36, 20), (255, 230, 160), (250, 170, 80), (226, 108, 40), (170, 64, 28), (255, 236, 120)),
    'leafstone': ((76, 54, 30), (238, 214, 160), (206, 168, 104), (168, 124, 70), (122, 88, 48), (78, 170, 70)),
    'icestone': ((60, 90, 120), (248, 254, 255), (210, 236, 250), (164, 206, 236), (120, 164, 206), (255, 255, 255)),
}

OUT = Path(__file__).resolve().parent.parent / 'assets/game/pixel/items/iconos'
for id, sim in SIMBOLO.items():
    o, h, w, m, s, x = PALETA[id]
    col = {'o': o, 'H': h, 'W': w, 'M': m, 'S': s}
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, fila in enumerate(PIEDRA.strip('\n').split('\n')):
        for xx, c in enumerate(fila):
            if c != '.': im.putpixel((xx, y), col[c] + (255,))
    for y, fila in enumerate(sim.strip('\n').split('\n')):
        for xx, c in enumerate(fila):
            if c == 'x': im.putpixel((xx, y + 1), x + (255,))
    im.save(OUT / f'{id}.png')
    if len(sys.argv) > 1: im.resize((96, 96), Image.NEAREST).save(Path(sys.argv[1]) / f'{id}_x6.png')
    print(OUT / f'{id}.png')
